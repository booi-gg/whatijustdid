import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { commitIndexForDirectory, stagedModifiedPaths, toGitPath } from "./git.mjs";
import { bulletLines, parseSubject } from "./providers/raw.mjs";
import { readEntryRecords } from "./store.mjs";

/** Read every canonical row. Explicit full scans remain available to API users. */
export function readEntries(dbDir) {
  return readEntryRecords(dbDir).map(({ entry }) => entry);
}

const abc = "abcdefghijklmnopqrstuvwxyz";

/** Map a stored entry to the shape changelog.html renders. */
function toGroup(entry, commit) {
  const parsed = parseSubject(commit.subject ?? "");
  const humanBullets = bulletLines(commit.body ?? "");
  const changes = entry.updatedAt && entry.changes?.length
    ? entry.changes
    : humanBullets.length
      ? humanBullets.map((summary) => ({ type: parsed.type, summary }))
      : entry.changes?.length
        ? entry.changes
        : parsed.title
          ? [{ type: parsed.type, summary: parsed.title }]
          : [{ type: entry.type ?? "other", summary: "Updated project files" }];

  return {
    kind: "commit",
    ref: commit.shortSha ?? entry.id?.slice(0, 7) ?? "change",
    author: commit.author ?? entry.author?.name ?? entry.author ?? "Unknown",
    date: commit.date ?? entry.createdAt ?? new Date(0).toISOString(),
    projects: entry.projects ?? [],
    link: null,
    entries: changes.map((change, i) => ({
      letter: `(${abc[i] ?? "+"})`,
      tags: [change.type ?? entry.type ?? "other"],
      description: change.summary,
    })),
  };
}

/**
 * Compile the file DB into changelog.data.js — a plain script that sets
 * window.__CHANGELOG__. Loaded by changelog.html; works over file:// (script
 * tags load local siblings, unlike fetch). This file is a rebuildable cache.
 */
export function build(config, options = {}) {
  const limit = Number.isInteger(config.limit) && config.limit > 0 ? config.limit : Infinity;
  const hasSuppliedIndex = Object.hasOwn(options, "commitIndex");
  const commitIndex = options.commitIndex
    ?? commitIndexForDirectory(
      config.root,
      config.dbDir,
      "HEAD",
      Number.isFinite(limit) ? limit : undefined,
    );
  const records = options.records
    ?? recordsForBuild(config, commitIndex, {
      fullScan: options.fullScan === true || (hasSuppliedIndex && !commitIndex.size),
      includeStaged: !hasSuppliedIndex,
    });
  const newestFirst = records
    .map(({ path: rowPath, entry }) => {
      const path = toGitPath(relative(config.root, rowPath));
      return toGroup(entry, entry.commit ?? commitIndex.get(path) ?? {});
    })
    .sort(compareGroupsNewestFirst);
  const groups = (Number.isFinite(limit) ? newestFirst.slice(0, limit) : newestFirst)
    .sort((a, b) => compareGroupsNewestFirst(b, a));
  const banner = "// GENERATED by changetrail — do not edit. Rebuild: changetrail build\n";
  const projects = Object.keys(config.projects);
  mkdirSync(dirname(config.dataFile), { recursive: true });
  writeFileSync(
    config.dataFile,
    `${banner}window.__CHANGELOG_PROJECTS__ = ${JSON.stringify(projects, null, 2)};\n` +
      `window.__CHANGELOG__ = ${JSON.stringify(groups, null, 2)};\n`,
  );
  return groups.length;
}

/**
 * Normal builds ask Git for only the latest row-adding commits, then read those
 * paths. A full recursive walk is reserved for an empty/new DB or an explicitly
 * supplied empty index (handy for non-Git API consumers and tests).
 */
function recordsForBuild(config, commitIndex, options = {}) {
  if (options.fullScan) return readEntryRecords(config.dbDir);

  const repositoryPaths = new Set(commitIndex.keys());
  if (options.includeStaged) {
    try {
      for (const path of stagedModifiedPaths(config.root, config.dbDir)) repositoryPaths.add(path);
    } catch {
      // A caller may build a directory that is not inside a Git repository.
    }
  }

  const paths = [...repositoryPaths]
    .filter((path) => path.endsWith(".json"))
    .map((path) => join(config.root, path))
    .filter(existsSync);
  return paths.length ? readEntryRecords(config.dbDir, paths) : readEntryRecords(config.dbDir);
}

function compareGroupsNewestFirst(a, b) {
  const dateDifference = dateValue(b.date) - dateValue(a.date);
  return dateDifference || String(b.ref).localeCompare(String(a.ref));
}

function dateValue(value) {
  const date = new Date(value).valueOf();
  return Number.isNaN(date) ? 0 : date;
}
